"""
============================================================
数据脱敏模块
============================================================

【功能说明】
数据脱敏是信息安全的重要技术，用于在展示数据时隐藏敏感部分，
既保证数据可用性，又保护隐私安全。

【脱敏原则】
1. 部分隐藏：只隐藏最敏感部分，保留必要信息
2. 可读性：脱敏后数据仍可识别和验证
3. 一致性：相同数据脱敏结果相同
4. 不可逆：无法从脱敏数据还原原始数据

【脱敏规则】
- 手机号：保留前3后4，中间隐藏
  13800138000 → 138****8000
  
- 身份证：保留前3后4，中间隐藏
  110101199001011234 → 110***********1234
  
- 银行卡：保留前4后4，中间隐藏
  6222021234567890 → 6222**********9012
  
- 邮箱：保留首字母，域名完整
  zhang@example.com → z***@example.com

【应用场景】
- 前端展示：用户列表、舆情列表
- 日志记录：审计日志脱敏记录
- 数据导出：导出报告时自动脱敏
- 第三方接口：对外提供数据时脱敏

【安全意义】
- 防止隐私泄露：即使数据库被窃取，也无法获取完整信息
- 合规要求：满足《个人信息保护法》要求
- 降低风险：降低数据泄露的危害程度
============================================================
"""


def mask_phone(phone: str) -> str:
    """
    手机号脱敏函数
    
    脱敏规则：
    保留前3位 + 后4位，中间用****替代
    例如：13800138000 → 138****8000
    
    原因：
    - 前3位：运营商识别码，可用于判断运营商
    - 后4位：用户号码，可用于唯一识别验证
    - 中间4位：最敏感，完全隐藏
    
    参数：
    phone：11位手机号字符串
    
    返回：
    脱敏后的手机号
    
    边界情况：
    - 长度<11：返回原值（可能不是手机号）
    - 空值：返回空值
    """
    if not phone or len(phone) < 11:
        return phone
    
    # 格式：前3位 + **** + 后4位
    return f"{phone[:3]}****{phone[-4:]}"


def mask_id_card(id_card: str) -> str:
    """
    身份证号脱敏函数
    
    脱敏规则：
    保留前3位 + 后4位，中间用11个*替代
    例如：110101199001011234 → 110***********1234
    
    原因：
    - 前3位：省份代码，可用于判断地区
    - 后4位：出生日期后2位 + 顺序码 + 校验码
    - 中间11位：出生日期完整信息 + 顺序码，最敏感
    
    身份证结构（18位）：
    1-6位：地区码
    7-14位：出生日期（YYYYMMDD）
    15-17位：顺序码（第17位奇数为男，偶数为女）
    18位：校验码
    
    参数：
    id_card：18位身份证号字符串
    
    返回：
    脱敏后的身份证号
    
    边界情况：
    - 长度<18：返回原值（可能不是身份证）
    - 空值：返回空值
    """
    if not id_card or len(id_card) < 18:
        return id_card
    
    # 格式：前3位 + 11个* + 后4位
    return f"{id_card[:3]}***********{id_card[-4:]}"


def mask_bank_card(bank_card: str) -> str:
    """
    银行卡号脱敏函数
    
    脱敏规则：
    保留前4位 + 后4位，中间用10个*替代
    例如：6222021234567890 → 6222**********9012
    
    原因：
    - 前4位：银行标识码（BIN），可用于判断银行
    - 后4位：校验位，可用于唯一识别验证
    - 中间10位：账户核心信息，最敏感
    
    银行卡结构（16-19位）：
    前6位：发卡行识别码（BIN）
    中间：账户号码
    最后1位：校验码
    
    参数：
    bank_card：16-19位银行卡号字符串
    
    返回：
    脱敏后的银行卡号
    
    边界情况：
    - 长度<16：返回原值（可能不是银行卡）
    - 空值：返回空值
    """
    if not bank_card or len(bank_card) < 16:
        return bank_card
    
    # 格式：前4位 + 10个* + 后4位
    return f"{bank_card[:4]}**********{bank_card[-4:]}"


def mask_email(email: str) -> str:
    """
    邮箱地址脱敏函数
    
    脱敏规则：
    保留首字母 + @ + 完整域名
    例如：zhang@example.com → z***@example.com
    
    原因：
    - 首字母：可用于模糊识别用户
    - 域名完整：保留邮箱服务商信息
    - 中间部分：用户名核心，完全隐藏
    
    邅箱结构：
    用户名 + @ + 域名
    
    参数：
    email：邮箱地址字符串
    
    返回：
    脱敏后的邮箱地址
    
    边界情况：
    - 不包含@：返回原值（可能不是邮箱）
    - 用户名长度≤1：返回*@域名
    - 空值：返回空值
    """
    if not email or '@' not in email:
        return email
    
    # 分割用户名和域名
    parts = email.split('@')
    username = parts[0]
    domain = parts[1]
    
    # 用户名长度≤1时，只显示*
    if len(username) <= 1:
        return f"*@{domain}"
    
    # 格式：首字母 + *** + @ + 域名
    return f"{username[0]}***@{domain}"


def mask_name(name: str) -> str:
    """
    姓名脱敏函数
    
    脱敏规则：
    保留首字，其余用*替代
    例如：张小明 → 张*明
    
    参数：
    name：姓名字符串
    
    返回：
    脱敏后的姓名
    """
    if not name:
        return name
    
    if len(name) <= 2:
        # 2字姓名：首字 + *
        return f"{name[0]}*"
    else:
        # 3字及以上：首字 + * + 最后字
        return f"{name[0]}*{name[-1]}"


def mask_sensitive_data(data: str, field_type: str) -> str:
    """
    统一脱敏接口
    
    功能：
    根据字段类型自动选择脱敏规则
    
    参数：
    data：原始数据字符串
    field_type：字段类型（phone/id_card/bank_card/email/name）
    
    返回：
    脱敏后的数据
    
    字段类型映射：
    - phone：手机号脱敏
    - id_card：身份证脱敏
    - bank_card：银行卡脱敏
    - email：邮箱脱敏
    - name：姓名脱敏
    - default：不脱敏（返回原值）
    
    应用场景：
    - 前端展示：统一调用此函数脱敏
    - 数据导出：导出时批量脱敏
    - API接口：对外接口自动脱敏
    """
    if field_type == "phone":
        return mask_phone(data)
    elif field_type == "id_card":
        return mask_id_card(data)
    elif field_type == "bank_card":
        return mask_bank_card(data)
    elif field_type == "email":
        return mask_email(data)
    elif field_type == "name":
        return mask_name(data)
    
    # 默认不脱敏
    return data